// DOCX Generator for Voice Agent Implementation Guides
// Generates professionally formatted DOCX files from deliverable data

const { Document, Paragraph, TextRun, HeadingLevel, AlignmentType, UnderlineType } = require('docx');

/**
 * Generate a professional DOCX document for a voice agent implementation guide
 * @param {Object} deliverable - Deliverable data with voice agent content
 * @param {string} companyName - Company name
 * @param {string} jobTitle - Job title/role
 * @param {string} industry - Industry context
 * @returns {Document} - DOCX document
 */
function generateVoiceAgentGuide(deliverable, companyName, jobTitle, industry) {
  const doc = new Document({
    sections: [{
      properties: {},
      children: [
        // Title Page
        createTitle(`AI Voice Agent Implementation Guide`),
        createSubtitle(`${deliverable.title}`),
        createSubtitle(`For ${jobTitle} at ${companyName}`),
        createEmptyLine(),
        createEmptyLine(),

        // Table of Contents (manual)
        createHeading('Contents', 1),
        ...createParagraph('1. Voice Agent Overview'),
        ...createParagraph('2. Personality & Communication Style'),
        ...createParagraph('3. Core Knowledge Base'),
        ...createParagraph('4. System Prompt & Instructions'),
        ...createParagraph('5. Sample Conversations'),
        ...createParagraph('6. Training Dialogues'),
        ...createParagraph('7. Integration Guide'),
        createEmptyLine(),
        createPageBreak(),

        // Section 1: Overview
        createHeading('1. Voice Agent Overview', 1),
        ...createBodyText(deliverable.voiceAgentOverview || 'Overview content will be generated by the AI.'),
        createEmptyLine(),
        createPageBreak(),

        // Section 2: Personality
        createHeading('2. Personality & Communication Style', 1),
        ...createBodyText(deliverable.voiceAgentPersonality || 'Personality content will be generated by the AI.'),
        createEmptyLine(),
        createPageBreak(),

        // Section 3: Knowledge Base
        createHeading('3. Core Knowledge Base', 1),
        ...createBodyText(deliverable.voiceAgentKnowledgeBase || 'Knowledge base content will be generated by the AI.'),
        createEmptyLine(),
        createPageBreak(),

        // Section 4: System Prompt
        createHeading('4. System Prompt & Instructions', 1),
        createSectionIntro('This is the complete system prompt you can use to configure your voice agent:'),
        createEmptyLine(),
        ...createCodeBlock(deliverable.voiceAgentSystemPrompt || 'System prompt will be generated by the AI.'),
        createEmptyLine(),
        createPageBreak(),

        // Section 5: Sample Conversations
        createHeading('5. Sample Conversations', 1),
        ...createBodyText(deliverable.voiceAgentSampleConversations || 'Sample conversations will be generated by the AI.'),
        createEmptyLine(),
        createPageBreak(),

        // Section 6: Training Data
        createHeading('6. Training Dialogues', 1),
        ...createBodyText(deliverable.voiceAgentTrainingData || 'Training data will be generated by the AI.'),
        createEmptyLine(),
        createPageBreak(),

        // Section 7: Integration
        createHeading('7. Integration & Technical Specifications', 1),
        ...createBodyText(deliverable.voiceAgentIntegrationGuide || 'Integration guide will be generated by the AI.'),
        createEmptyLine(),

        // Footer
        createPageBreak(),
        createEmptyLine(),
        createEmptyLine(),
        ...createParagraph('---'),
        createEmptyLine(),
        ...createBodyText(`Generated by AIVA ROI Calculator for ${companyName}`, true),
        ...createBodyText(`Industry: ${industry}`, true),
        ...createBodyText(`Role: ${jobTitle}`, true),
        ...createBodyText(`Deliverable: ${deliverable.title}`, true),
      ]
    }]
  });

  return doc;
}

// Helper functions for document formatting

function createTitle(text) {
  return new Paragraph({
    text: text,
    heading: HeadingLevel.TITLE,
    alignment: AlignmentType.CENTER,
    spacing: { after: 400 }
  });
}

function createSubtitle(text) {
  return new Paragraph({
    text: text,
    alignment: AlignmentType.CENTER,
    spacing: { after: 200 },
    children: [
      new TextRun({
        text: text,
        size: 28,
        color: '666666'
      })
    ]
  });
}

function createHeading(text, level) {
  const headingLevel = level === 1 ? HeadingLevel.HEADING_1 : HeadingLevel.HEADING_2;
  return new Paragraph({
    text: text,
    heading: headingLevel,
    spacing: { before: 400, after: 200 }
  });
}

function createSectionIntro(text) {
  return new Paragraph({
    children: [
      new TextRun({
        text: text,
        italics: true,
        color: '555555'
      })
    ],
    spacing: { after: 200 }
  });
}

function createBodyText(text, isItalic = false) {
  // Split text into paragraphs
  const paragraphs = text.split('\n').filter(p => p.trim() !== '');

  return paragraphs.map(para => {
    // Check if it's a header (has ** or is all caps with colon)
    const isHeader = para.includes('**') || (/^[A-Z\s]+:/.test(para) && para.split(':')[0].length < 40);

    if (isHeader) {
      // Remove ** markers and create bold header
      const cleanText = para.replace(/\*\*/g, '');
      return new Paragraph({
        children: [
          new TextRun({
            text: cleanText,
            bold: true,
            size: 24
          })
        ],
        spacing: { before: 200, after: 100 }
      });
    }

    return new Paragraph({
      children: [
        new TextRun({
          text: para,
          italics: isItalic
        })
      ],
      spacing: { after: 100 }
    });
  });
}

function createCodeBlock(text) {
  const lines = text.split('\n');

  return lines.map(line => {
    return new Paragraph({
      children: [
        new TextRun({
          text: line,
          font: 'Courier New',
          size: 20,
          color: '333333'
        })
      ],
      spacing: { after: 50 },
      indent: { left: 720 } // 0.5 inch indent
    });
  });
}

function createParagraph(text) {
  return [new Paragraph({
    children: [
      new TextRun({
        text: text
      })
    ],
    spacing: { after: 100 }
  })];
}

function createEmptyLine() {
  return new Paragraph({
    text: '',
    spacing: { after: 200 }
  });
}

function createPageBreak() {
  return new Paragraph({
    text: '',
    pageBreakBefore: true
  });
}

module.exports = {
  generateVoiceAgentGuide
};
